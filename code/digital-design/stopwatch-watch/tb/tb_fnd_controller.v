`timescale 1ns / 1ps

module tb_fnd_controller;

    // --------------------------------------------------
    // 1. 신호 선언
    // --------------------------------------------------
    reg        clk;
    reg        rst;
    reg        sw;       // sw[1] 역할: 0=[시:분], 1=[초:밀리초]
    reg  [1:0] i_state;  // 00:NORMAL, 01:SET_SEC, 10:SET_MIN, 11:SET_HOUR
    
    // 화면에 띄울 가짜(Dummy) 시간 데이터
    reg  [6:0] msec;
    reg  [5:0] sec;
    reg  [5:0] min;
    reg  [4:0] hour;

    wire [7:0] fnd_data; // 7-Segment 데이터 (최상위 비트 또는 최하위 비트가 DP)
    wire [3:0] fnd_com;  // 자릿수 선택 신호 (0111, 1011, 1101, 1110)

    // --------------------------------------------------
    // 2. DUT (Device Under Test) 인스턴스화
    // --------------------------------------------------
    fnd_controller DUT (
        .clk      (clk),
        .rst      (rst),
        .sw       (sw),
        .i_state  (i_state),
        .msec     (msec),
        .sec      (sec),
        .min      (min),
        .hour     (hour),
        .fnd_data (fnd_data),
        .fnd_com  (fnd_com)
    );

    // --------------------------------------------------
    // 3. 클럭 생성 (100MHz -> 10ns 주기)
    // --------------------------------------------------
    always #5 clk = ~clk;

    // --------------------------------------------------
    // 4. 도트(DP) 동작 검증 시나리오
    // --------------------------------------------------
    initial begin
        // 초기화 및 가짜 데이터 주입 (12시 34분 56초 78밀리초)
        clk = 0; rst = 1;
        sw = 0; i_state = 2'b00;
        msec = 7'd78; sec = 6'd56; min = 6'd34; hour = 5'd12;
        
        #20 rst = 0;

        // ==========================================
        // 시나리오 1: [시:분] 화면 & NORMAL 모드
        // 예상 결과: 가운데 콜론(in6, 시 1의 자리)만 깜빡여야 함!
        // ==========================================
        $display("--- Scenario 1: [Hour:Min] NORMAL ---");
        sw = 0; i_state = 2'b00; 
        #500_000; // 도트가 깜빡일 때까지 충분히 대기 (시간 단축 팁 적용 시)

        // ==========================================
        // 시나리오 2: [시:분] 화면 & 분 설정(SET_MIN) 모드
        // 예상 결과: 오른쪽 두 자리(in4, in5) 아래 점이 깜빡여야 함!
        // ==========================================
        $display("--- Scenario 2: [Hour:Min] SET_MIN ---");
        sw = 0; i_state = 2'b10;
        #500_000;

        // ==========================================
        // 시나리오 3: [초:밀리초] 화면 전환 (sw=1) & NORMAL 모드
        // 예상 결과: 가운데 콜론(in6, 초 1의 자리)만 깜빡여야 함!
        // ==========================================
        $display("--- Scenario 3: [Sec:Msec] NORMAL ---");
        sw = 1; i_state = 2'b00;
        #500_000;

        // ==========================================
        // 시나리오 4: [초:밀리초] 화면 & 초 설정(SET_SEC) 모드 ★(아까 수정한 부분)
        // 예상 결과: 왼쪽 두 자리(in6, in7) 아래 점이 깜빡여야 함!
        // ==========================================
        $display("--- Scenario 4: [Sec:Msec] SET_SEC ---");
        sw = 1; i_state = 2'b01;
        #500_000;

        $finish;
    end

endmodule